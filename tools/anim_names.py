"""Animation names of Hitman 2's scenes (for Lua npc:animation(name)).

The scene's .ANM (docs/models.md): one chunk tree; chunk 0xA is an animation
set (its data: the set's name, e.g. Worlds\\Characters\\_Anims\\Reg_Male\\
Reg_Male.anm) with one child listing the offsets of its animations' 0x84-byte
records in chunk 5, a record starting with the animation's name.

  python anim_names.py <game dir> [out.md]     every level's sets and names
"""
import os
import struct
import sys
import zipfile


def u32(b, o):
    return struct.unpack_from("<I", b, o)[0]


def chunk(b, p):
    """(tag, size, data offset, children [(pos)])"""
    tag, sf = u32(b, p), u32(b, p + 4)
    size = sf & 0x3FFFFFFF
    if not sf & 0x80000000:
        return tag, size, p + 8, []
    data = p + u32(b, p + 8)
    count = u32(b, p + 0xC)
    q = p + 0x10
    if sf & 0x40000000:
        q += 4 + 4 * u32(b, q)
    kids = []
    for _ in range(count):
        if q + 8 > p + size or q + 8 > len(b):
            break
        kids.append(q)
        q += u32(b, q + 4) & 0x3FFFFFFF
    return tag, size, data, kids


def cstr(b, o, n=64):
    e = b.find(b"\0", o, o + n)
    return b[o:e if e >= 0 else o + n].decode("latin-1")


def sets(anm):
    tag, size, data, kids = chunk(anm, 0)
    tops = {}
    for k in kids:
        t = u32(anm, k)
        tops.setdefault(t, []).append(k)
    if 5 not in tops:
        return {}
    _, _, anims, _ = chunk(anm, tops[5][0])
    out = {}
    for s in tops.get(0xA, []):
        _, _, sdata, skids = chunk(anm, s)
        name = cstr(anm, sdata, 260)
        names = []
        if skids:
            _, csize, cdata, _ = chunk(anm, skids[0])
            n = u32(anm, skids[0])  # the child's tag is the animation count
            for i in range(n):
                off = u32(anm, cdata + 4 * i)
                names.append(cstr(anm, anims + off))
        out[name] = names
    return out


def main():
    game = sys.argv[1]
    out = open(sys.argv[2], "w", encoding="utf-8") if len(sys.argv) > 2 else sys.stdout
    scenes = os.path.join(game, "Scenes")
    by_set = {}
    for level in sorted(os.listdir(scenes)):
        z = os.path.join(scenes, level, level + "__MAIN.ZIP")
        if not os.path.exists(z):
            continue
        with zipfile.ZipFile(z) as f:
            name = "SCENES/%s/%s__MAIN.ANM" % (level, level)
            try:
                anm = f.read(name)
            except KeyError:
                continue
        for s, names in sets(anm).items():
            entry = by_set.setdefault(s, {"levels": [], "names": set()})
            entry["levels"].append(level)
            entry["names"].update(n for n in names if n)
    out.write("# Animations by set\n\nGenerated by tools/anim_names.py. A character plays the "
              "animations of its sets (its data block names them): `npc:animation(name [, loop])`.\n")
    for s in sorted(by_set):
        e = by_set[s]
        short = s.replace("\\", "/").split("/")[-1]
        out.write("\n## %s\n\n`%s` (%s)\n\n" % (short, s, ", ".join(e["levels"])))
        out.write(", ".join("`%s`" % n for n in sorted(e["names"], key=str.lower)) + "\n")


if __name__ == "__main__":
    main()
